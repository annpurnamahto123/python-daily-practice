#- Percentage contribution of each category to total revenue.
category_data = {}
total_revenue = 0

for i in sales:
    if i["category"] not in category_data:
        category_data[i["category"]] = {"category_revenue": 0}
    category_data[i["category"]]["category_revenue"] += i["quantity"] * i["price"]

