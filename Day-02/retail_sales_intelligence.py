#Q1. Calculate revenue for every transaction using quantity × price, then calculate total store revenue.
order_data = {}
total_revenue = 0

for i in sales:
    if i["order_id"] not in order_data:
        order_data[i["order_id"]]= {"revenue" : 0}
    order_data[i["order_id"]]["revenue"] = i["quantity"] * i["price"]

for order_id, data in order_data.items():
    total_revenue = total_revenue + data["revenue"] 

print(order_data)
print("Total Revenue:", total_revenue)


#Q2. Find: - Total quantity sold for each product. - Total revenue generated by each product.
product_data = {}
for i in sales:
    if i["product"] not in product_data:
        product_data[i["product"]] = {"quantity": 0, "total_revenue": 0}
    product_data[i["product"]]["quantity"] += i["quantity"]
    product_data[i["product"]]["total_revenue"] += i["quantity"] * i["price"]

print(product_data)


#Q3. Calculate total spending by each customer. Identify the highest-spending customer.

customer_data = {}
highest_spending = 0
highest_customer = ""

for i in sales:
    if i["customer"] not in customer_data:
        customer_data[i["customer"]] = {"total_spending": 0}
    customer_data[i["customer"]]["total_spending"] += i["quantity"] * i["price"]

for customer, data in customer_data.items():
    if data["total_spending"] > highest_spending:
        highest_spending = data["total_spending"]
        highest_customer = customer
    
print(customer_data)
print("Highest Spending Customer:", highest_customer)
print("Total Spending:", highest_spending)


